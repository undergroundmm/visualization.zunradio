// ZUN radio scene: dots, rings and waves moving with the music, as on zunradio.cz
// (scena.js) and in the "Pecka dne" videos. Platform independent part: audio analysis,
// motion and the list of shapes to draw. Main_gl.cpp and Main_dx.cpp draw the shapes.

#pragma once

#include <cstddef>
#include <cstdint>
#include <deque>
#include <mutex>
#include <vector>

namespace zun
{

// Layout in the 1920 x 1080 space of Kodi skins, shared with the scene window of
// plugin.audio.zunradio (resources/skins/Default/1080i/zunradio-scena.xml).
constexpr float SPACE_W = 1920.0f;
constexpr float SPACE_H = 1080.0f;
constexpr float CARD_CX = 960.0f; // centre of the cover card
constexpr float CARD_CY = 496.0f;
constexpr float CARD_SIDE = 514.0f; // red card including its frame
constexpr float CARD_FRAME = 22.0f; // red frame around the cover

// The pulse of the basses for the scene window, reported as the active preset (index into
// PRESETS): "zun" calm, l/p = tilt of the fields to the left or right (changes with every beat),
// then the digits of all reached levels of the pulse (1 to PULSE_LEVELS). The window builds the
// motion of the cover and the fields from one animation per level, so it pumps with the bass as
// on the web, small changes included (Visualisation.Preset in zunradio-scena.xml of
// plugin.audio.zunradio, generated by nastroje/scena_animace.py). The flash of the card on every
// 8th beat is reported as Visualisation.Locked.
constexpr int PULSE_LEVELS = 8;
// The window gets the peak at once and holds it for the time of its animation (60 ms), then it
// follows the decay of the web: fast up, slow down (Lada 2026-11-08: "rychleji vyskakuje, nez se vraci")
constexpr double PEAK_HOLD_MS = 60.0;
constexpr const char* PRESETS[] = {
    "zun",      "l1",      "l12",      "l123",      "l1234",      "l12345",      "l123456",
    "l1234567", "l12345678", "p1",     "p12",       "p123",       "p1234",       "p12345",
    "p123456",  "p1234567", "p12345678"};
constexpr double FLASH_MS = 100.0;

enum ShapeType : int
{
  SHAPE_DISC = 0, // filled circle
  SHAPE_RING = 1, // circle outline
  SHAPE_SQUARE_RING = 2, // rectangle outline
  SHAPE_FILL = 3, // solid rectangle
  SHAPE_GLOW = 4, // radial light growing to the edges
};

// One quad in pixels of the visualisation area. u, v run from -1 to 1 over the quad.
struct Shape
{
  int type;
  float cx, cy; // centre
  float hw, hh; // half width and height
  float r, g, b, a;
  float thickness; // part of the half size (rings) or inner radius (glow), 0..1
  float aa; // antialiasing width in u, v units
};

// One vertex as the shaders expect it (Main_gl.cpp, Main_dx.cpp)
struct Vertex
{
  float x, y; // pixels
  float u, v;
  float r, g, b, a;
  float type, thickness, aa;
};

class Band
{
public:
  float pulse = 0.0f;
  float Update(float energy, double t, double dt);
  void Decay(double dt);

private:
  bool m_hasOld = false;
  float m_old = 0.0f;
  double m_oldTime = 0.0;
  std::deque<float> m_rises;
  float m_ceiling = 3.0f;
  int m_sinceCeiling = 0;
};

// Second order IIR filter (RBJ cookbook), direct form I
class Biquad
{
public:
  void LowPass(float rate, float freq);
  void HighPass(float rate, float freq);
  float Process(float x);

private:
  float b0 = 1, b1 = 0, b2 = 0, a1 = 0, a2 = 0;
  float x1 = 0, x2 = 0, y1 = 0, y2 = 0;
};

// Mean square of the last N samples
class Energy
{
public:
  explicit Energy(size_t n) : m_buf(n, 0.0f) {}
  void Push(float x);
  float Value() const { return static_cast<float>(m_sum / m_buf.size()); }

private:
  std::vector<float> m_buf;
  size_t m_pos = 0;
  double m_sum = 0.0;
  int m_sinceExact = 0;
};

// Threads: Kodi calls AudioData from its audio thread (when the samples are due, in step with
// the output), Render from the render thread and GetActivePreset from the GUI thread. The analysis
// runs with the audio data, so it does not depend on how often a window is drawn (LibreELEC draws
// covered parts of the screen only when they change). The others read the state at their own time.
class Scene
{
public:
  Scene();
  static double Now(); // steady clock in milliseconds, the same for all threads
  void Start(int channels, int samplesPerSec);
  void AudioData(const float* data, size_t length);
  // Shapes for an area of width x height pixels at time t
  void Frame(double t, float width, float height, bool card, std::vector<Shape>& shapes);
  static void ToVertices(const std::vector<Shape>& shapes, std::vector<Vertex>& vertices);
  // Index into PRESETS for the pulse of the basses at time t
  int PulseState(double t);
  // The flash of the card on every 8th beat
  bool Flash(double t);
  // Debug line about the analysis every 10 s (false otherwise)
  bool Report(double t, char* text, size_t size);

private:
  struct Element
  {
    float x, y, r;
    float ax, ay, f, phase;
    float px, py, pfx, pfy, pphx, pphy;
  };
  void Layout();
  void Analyse(double t);
  void Beat(double t, float strength);
  float BassAt(double t) const;
  float TrebleAt(double t) const;
  float WindowPulseAt(double t) const;
  void Position(const Element& e, double sec, float bounce, float& x, float& y) const;

  std::mutex m_mutex;
  int m_channels = 2;
  float m_rate = 48000.0f;
  Biquad m_lp1, m_lp2, m_hp;
  Energy m_bassEnergy{2048};
  Energy m_trebleEnergy{1024};
  bool m_hasAudio = false;

  Band m_bass, m_treble; // pulses as of m_lastAnalysis
  double m_lastAnalysis = -1.0;
  int m_beats = 0;
  double m_lastBeat = -1e9;
  int m_direction = 1; // tilt of the fields changes with every beat
  double m_flashUntil = 0.0;
  float m_peak = 0.0f; // peak of the bass pulse for the scene window, held PEAK_HOLD_MS
  double m_peakTime = 0.0;
  double m_flashLight = 0.0; // when the light after a flash starts
  std::vector<double> m_waves;

  // render thread only
  double m_lastFrame = -1.0;
  double m_start = -1.0;
  float m_light = 0.0f;
  double m_lastReport = 0.0;
  std::vector<Element> m_dots, m_rings;
};

} // namespace zun
